-- 航小鱼交易模块：独立 PostgreSQL 建表草案，2026-11-12
-- 仅用于评审交易模块模式；trade_demo.user_stub/listing_stub 是小组接口占位表。
-- 已于 2026-11-13 在本机 PostgreSQL 18.7 的 hangxiaoyu_trade_demo 数据库实跑通过。
-- 这仅验证独立演示模式的建表与初始化；小组确定 User/Listing 后，仍需替换占位表及外键。
-- 此脚本首次运行创建 trade_demo schema；不包含 DROP，不会覆盖小组表。

BEGIN;
CREATE SCHEMA trade_demo;

CREATE TABLE trade_demo.user_stub (
    user_id BIGINT PRIMARY KEY,
    display_name TEXT NOT NULL
);

CREATE TABLE trade_demo.listing_stub (
    listing_id BIGINT PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES trade_demo.user_stub(user_id),
    current_price_points BIGINT NOT NULL CHECK (current_price_points > 0),
    status TEXT NOT NULL CHECK (status IN
        ('ON_SALE', 'PAYMENT_RESERVED', 'TRADING', 'RELIST_BUFFER', 'OFF_SHELF', 'SOLD'))
);

CREATE TABLE trade_demo.point_account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type TEXT NOT NULL CHECK (owner_type IN ('USER', 'PLATFORM_ESCROW')),
    user_id BIGINT REFERENCES trade_demo.user_stub(user_id),
    balance_points BIGINT NOT NULL DEFAULT 0 CHECK (balance_points >= 0),
    CONSTRAINT point_account_owner_shape CHECK (
        (owner_type = 'USER' AND user_id IS NOT NULL)
        OR (owner_type = 'PLATFORM_ESCROW' AND user_id IS NULL)
    ),
    CONSTRAINT one_account_per_user UNIQUE (user_id)
);

CREATE UNIQUE INDEX one_platform_escrow_account
ON trade_demo.point_account (owner_type)
WHERE owner_type = 'PLATFORM_ESCROW';

INSERT INTO trade_demo.point_account (owner_type, user_id, balance_points)
VALUES ('PLATFORM_ESCROW', NULL, 0);

CREATE TABLE trade_demo.trade_order (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES trade_demo.listing_stub(listing_id),
    buyer_id BIGINT NOT NULL REFERENCES trade_demo.user_stub(user_id),
    price_snapshot_points BIGINT NOT NULL CHECK (price_snapshot_points > 0),
    status TEXT NOT NULL CHECK (status IN
        ('PENDING_PAYMENT', 'PENDING_DELIVERY', 'PENDING_RECEIPT',
         'UNDER_REVIEW', 'COMPLETED', 'CANCELED', 'PAYMENT_EXPIRED')),
    created_at TIMESTAMPTZ NOT NULL,
    payment_deadline_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    auto_complete_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    completion_method TEXT CHECK (completion_method IN ('BUYER_CONFIRMED', 'AUTO')),
    canceled_at TIMESTAMPTZ,
    cancel_reason TEXT,
    CONSTRAINT payment_deadline_after_order CHECK (payment_deadline_at > created_at),
    CONSTRAINT completion_fields_together CHECK (
        (completed_at IS NULL AND completion_method IS NULL)
        OR (completed_at IS NOT NULL AND completion_method IS NOT NULL)
    )
);

-- 历史订单可有多笔，但同一商品最多一笔有效订单。
CREATE UNIQUE INDEX one_active_order_per_listing
ON trade_demo.trade_order (listing_id)
WHERE status IN ('PENDING_PAYMENT', 'PENDING_DELIVERY', 'PENDING_RECEIPT', 'UNDER_REVIEW');

CREATE TABLE trade_demo.point_transfer (
    transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES trade_demo.trade_order(order_id),
    event_type TEXT NOT NULL CHECK (event_type IN ('PAYMENT', 'SETTLEMENT', 'REFUND')),
    occurred_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT one_transfer_per_order_event UNIQUE (order_id, event_type)
);

CREATE TABLE trade_demo.balance_ledger (
    ledger_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES trade_demo.point_transfer(transfer_id),
    account_id BIGINT NOT NULL REFERENCES trade_demo.point_account(account_id),
    delta_points BIGINT NOT NULL CHECK (delta_points <> 0),
    CONSTRAINT one_ledger_side_per_account UNIQUE (transfer_id, account_id)
);

CREATE TABLE trade_demo.price_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES trade_demo.listing_stub(listing_id),
    price_points BIGINT NOT NULL CHECK (price_points > 0),
    change_type TEXT NOT NULL CHECK (change_type IN ('INITIAL', 'REPRICE')),
    changed_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX one_initial_price_per_listing
ON trade_demo.price_history (listing_id)
WHERE change_type = 'INITIAL';

CREATE TABLE trade_demo.order_review (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES trade_demo.trade_order(order_id),
    reason TEXT NOT NULL CHECK (reason IN
        ('BUYER_CANCEL_REQUEST', 'NOT_RECEIVED', 'SELLER_DELIVERY_LATE')),
    previous_status TEXT NOT NULL CHECK (previous_status IN
        ('PENDING_DELIVERY', 'PENDING_RECEIPT')),
    opened_at TIMESTAMPTZ NOT NULL,
    decision TEXT CHECK (decision IN ('CANCEL', 'CONTINUE')),
    resolved_at TIMESTAMPTZ,
    admin_id BIGINT REFERENCES trade_demo.user_stub(user_id),
    CONSTRAINT review_resolution_together CHECK (
        (decision IS NULL AND resolved_at IS NULL AND admin_id IS NULL)
        OR (decision IS NOT NULL AND resolved_at IS NOT NULL AND admin_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX one_open_review_per_order
ON trade_demo.order_review (order_id)
WHERE resolved_at IS NULL;

CREATE TABLE trade_demo.score_event (
    score_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES trade_demo.trade_order(order_id),
    user_id BIGINT NOT NULL REFERENCES trade_demo.user_stub(user_id),
    score_type TEXT NOT NULL CHECK (score_type IN ('BUYER_REWARD', 'SELLER_REPUTATION')),
    reason TEXT NOT NULL CHECK (reason IN ('COMPLETION', 'VERIFIED_DELIVERY_LATE')),
    delta_score INTEGER NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    operator_id BIGINT REFERENCES trade_demo.user_stub(user_id),
    CONSTRAINT one_score_event_per_order_reason UNIQUE (order_id, score_type, reason)
);

COMMIT;

-- 仍需原生 SQL 事务、存储过程或触发器保障：
-- 1. 每次 point_transfer 恰有两条不同账户流水，delta_points 求和为 0，金额等于订单价格。
-- 2. point_account.balance_points 与流水同步；平台余额等于所有未结算/未退款订单托管额。
-- 3. SETTLEMENT 与 REFUND 互斥；订单、商品、账户、流水、评分一次原子提交。
-- 4. 商品卖家不可购买自己商品；商品当前价等于最后一次成功的 price_history 价格。
-- 5. 支付超时、交付超时、未收到反馈与自动完成按数据库时间和原状态判定。
